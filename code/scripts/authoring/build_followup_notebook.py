    for cell in cells:
        if cell['cell_type']=='code':compile(''.join(cell['source']),cell['id'],'exec')
    notebook={'nbformat':4,'nbformat_minor':5,'metadata':{'kernelspec':{'display_name':'Python 3','language':'python','name':'python3'}},'cells':cells}
